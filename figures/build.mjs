// Builds the chapter figures into dist/figures/.
//
//   node figures/build.mjs                 every chapter that has figures/cNN/figure.mjs
//   node figures/build.mjs --only 19,6     selected chapters
//   node figures/build.mjs --only 19 --audit   also run the figure's geometry audit (figure decides what it checks)
//
// Output:
//   dist/figures/kit.js     the vendored kit as browser globals (window.IsoKit = { k, G, tube, gl })
//   dist/figures/iso.css    the kit's styles
//   dist/figures/cNN.js     one classic script per chapter: registers window.COURSE_FIGURES[NN]
//
// Each chapter lives in figures/cNN/:
//   figure.mjs     export async function build({ audit, argv }) → { markup, data }
//   live.js        export default function mount(root, ctx, K, DATA) { … return { update, destroy } }
//   strings.json   { "en": { "title": …, … }, "id": { … } }  → synced into dist/locales/*.json as fig.cNN.*
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// Readers (the dev server, the tests, parallel builds) must never see a half-written file.
function atomicWrite(file, text) {
  const temp = `${file}.${process.pid}.tmp`;
  writeFileSync(temp, text);
  renameSync(temp, file);
}

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const DIST = join(ROOT, "dist");
const OUT = join(DIST, "figures");
const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const option = (name) => {
  const at = argv.indexOf(name);
  return at < 0 ? null : argv[at + 1];
};
const pad = (id) => String(id).padStart(2, "0");

mkdirSync(OUT, { recursive: true });

// ---------- kit runtime ----------
// Each kit module runs in its own function scope (they share some private helper names), its imports
// become destructured locals from the modules before it, and its exports become the returned object.
function wrap(file, name, imports) {
  let source = readFileSync(join(HERE, "kit", file), "utf8");
  const names = [...source.matchAll(/^export (?:async function|function|const|let|class) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
  source = source.replace(/^export /gm, "");
  source = source.replace(/^import \* as (\w+) from "\.\/([\w-]+)\.mjs";$/gm, (_, local, mod) => `const ${local} = ${imports[mod]};`);
  source = source.replace(/^import \{([^}]*)\} from "\.\/([\w-]+)\.mjs";$/gm, (_, list, mod) => `const {${list.replace(/\bas\b/g, ":")}} = ${imports[mod]};`);
  if (/^import /m.test(source)) throw new Error(`unhandled import in ${file}`);
  return `const ${name} = (() => {\n${source}\nreturn { ${names.join(", ")} };\n})();\n`;
}
function kitRuntime() {
  const mods = { "iso-kit": "__k", lathe: "__G", tube: "__tube", gl: "__gl" };
  const body = wrap("iso-kit.mjs", "__k", mods) + wrap("lathe.mjs", "__G", mods) + wrap("tube.mjs", "__tube", mods) + wrap("gl.mjs", "__gl", mods);
  return `/* Generated by figures/build.mjs from figures/kit (anatomy kit, MIT). Do not edit. */\n(() => {\n"use strict";\n${body}window.IsoKit = Object.freeze({ k: __k, G: __G, tube: __tube, gl: __gl });\n})();\n`;
}

// ---------- strings ----------
const LOCALES = ["id", "en"];
const catalogPath = (code) => join(DIST, "locales", `${code}.json`);
const params = (text) => [...text.matchAll(/\{([a-zA-Z][\w]*)\}/g)].map((m) => m[1]).sort().join("|");
const SHARED = { id: { "fig.ui.number": "Gbr {number}" }, en: { "fig.ui.number": "Fig {number}" } };

function withLock(fn) {
  const lock = join(HERE, ".catalog-lock");
  const start = Date.now();
  for (;;) {
    try {
      mkdirSync(lock);
      break;
    } catch {
      if (Date.now() - start > 30000) throw new Error(`catalog lock held for 30 s: remove ${lock} if no build is running`);
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 50);
    }
  }
  try {
    return fn();
  } finally {
    rmdirSync(lock);
  }
}

function chapterOf(key) {
  const match = key.match(/^fig\.c(\d\d)\./);
  return match ? Number(match[1]) : key.startsWith("fig.") ? 0 : -1;
}

function syncStrings(id, strings) {
  const prefix = `fig.c${pad(id)}.`;
  for (const code of LOCALES) if (!strings[code] || typeof strings[code] !== "object") throw new Error(`c${pad(id)} strings.json: missing "${code}"`);
  const names = Object.keys(strings.en);
  const idNames = Object.keys(strings.id);
  const missing = names.filter((n) => !(n in strings.id)).concat(idNames.filter((n) => !(n in strings.en)));
  if (missing.length) throw new Error(`c${pad(id)} strings.json: keys not in both languages: ${missing.join(", ")}`);
  for (const name of names) {
    for (const code of LOCALES) if (typeof strings[code][name] !== "string" || !strings[code][name].length) throw new Error(`c${pad(id)} strings.json: ${code}.${name} must be a non-empty string`);
    if (params(strings.en[name]) !== params(strings.id[name])) throw new Error(`c${pad(id)} strings.json: placeholder mismatch in ${name}`);
  }
  withLock(() => {
    for (const code of LOCALES) {
      const catalog = JSON.parse(readFileSync(catalogPath(code), "utf8"));
      const next = {};
      for (const [key, value] of Object.entries(catalog)) if (!key.startsWith(prefix) && !(key in SHARED[code])) next[key] = value;
      Object.assign(next, SHARED[code]);
      for (const name of names) next[prefix + name] = strings[code][name];
      // Keep the figure keys grouped after the course keys, ordered by chapter.
      const entries = Object.entries(next);
      const course = entries.filter(([key]) => chapterOf(key) < 0);
      const figures = entries.filter(([key]) => chapterOf(key) >= 0).sort((a, b) => chapterOf(a[0]) - chapterOf(b[0]));
      atomicWrite(catalogPath(code), JSON.stringify(Object.fromEntries([...course, ...figures]), null, 2) + "\n");
    }
  });
  return names.map((name) => prefix + name);
}

// ---------- chapters ----------
function chapters() {
  const only = option("--only");
  const all = readdirSync(HERE)
    .map((name) => name.match(/^c(\d\d)$/))
    .filter(Boolean)
    .map((m) => Number(m[1]))
    .filter((id) => existsSync(join(HERE, `c${pad(id)}`, "figure.mjs")))
    .sort((a, b) => a - b);
  if (!only) return all;
  const wanted = only.split(",").map(Number);
  for (const id of wanted) if (!all.includes(id)) throw new Error(`no figures/c${pad(id)}/figure.mjs`);
  return wanted;
}

async function buildChapter(id) {
  const dir = join(HERE, `c${pad(id)}`);
  const started = Date.now();
  const mod = await import(pathToFileURL(join(dir, "figure.mjs")).href);
  const out = await mod.build({ audit: flag("--audit"), argv });
  if (!out || typeof out.markup !== "string") throw new Error(`c${pad(id)}: build() must return { markup, data }`);
  const live = readFileSync(join(dir, "live.js"), "utf8");
  if (!/^export default function mount\(/m.test(live)) throw new Error(`c${pad(id)}/live.js must start its mount with "export default function mount("`);
  if (/^\s*import\s/m.test(live)) throw new Error(`c${pad(id)}/live.js must not import: use K (the kit) and DATA`);
  const strings = JSON.parse(readFileSync(join(dir, "strings.json"), "utf8"));
  const keys = syncStrings(id, strings);
  const used = [...out.markup.matchAll(/data-fig-(?:text|aria)="([^"]+)"/g)].map((m) => m[1]);
  const known = new Set([...keys, ...Object.keys(SHARED.en)]);
  const unknown = [...new Set(used.filter((key) => !known.has(key)))];
  if (unknown.length) throw new Error(`c${pad(id)}: markup uses keys missing from strings.json: ${unknown.join(", ")}`);
  const script =
    `/* Generated by figures/build.mjs from figures/c${pad(id)}. Do not edit. */\n(() => {\n"use strict";\n` +
    `const DATA = ${JSON.stringify(out.data ?? {})};\n` +
    `const MARKUP = ${JSON.stringify(out.markup)};\n` +
    live.replace(/^export default function mount\(/m, "function mount(") +
    `\n(window.COURSE_FIGURES = window.COURSE_FIGURES || {})[${id}] = { id: ${id}, markup: MARKUP, data: DATA, mount };\n})();\n`;
  // Fails the build on a syntax error in live.js, before a browser ever sees it.
  new Function(script);
  atomicWrite(join(OUT, `c${pad(id)}.js`), script);
  console.log(`c${pad(id)}  ${(script.length / 1024).toFixed(0)} KB  ${keys.length} strings  ${Date.now() - started} ms`);
}

// Shared outputs are rewritten only when they change, so parallel single-chapter builds never truncate them under a reader.
function writeIfChanged(file, text) {
  if (existsSync(file) && readFileSync(file, "utf8") === text) return;
  atomicWrite(file, text);
}
const runtime = kitRuntime();
new Function(runtime);
writeIfChanged(join(OUT, "kit.js"), runtime);
writeIfChanged(join(OUT, "iso.css"), `/* Generated by figures/build.mjs from figures/kit/iso.css (anatomy kit, MIT). Do not edit. */\n` + readFileSync(join(HERE, "kit", "iso.css"), "utf8"));
let failed = 0;
for (const id of chapters()) {
  try {
    await buildChapter(id);
  } catch (error) {
    failed++;
    console.error(`c${pad(id)} failed: ${error.stack || error.message}`);
  }
}
if (failed) process.exitCode = 1;
